const INK = '#1b1b1f';
const CYAN = '#06b6d4';
const GRAY = '#9a9aa2';

type Pt = { x: number; y: number };
type Raw = [number, number];

const pts = (...raw: Raw[]): Pt[] => raw.map(([x, y]) => ({ x, y }));

const arc = (cx: number, cy: number, r: number, a0 = 0, a1 = Math.PI * 2, n = 26): Pt[] => {
  const out: Pt[] = [];
  for (let i = 0; i <= n; i += 1) {
    const a = a0 + ((a1 - a0) * i) / n;
    out.push({ x: cx + r * Math.cos(a), y: cy + r * 1.6 * Math.sin(a) });
  }
  return out;
};

const circle = (cx: number, cy: number, r: number): Pt[] => arc(cx, cy, r);

const s = (points: Pt[], color = INK, size = 5): Stroke => ({ color, size, tool: 'pen', points });

const star = (cx: number, cy: number, r: number): Pt[] => {
  const out: Pt[] = [];
  for (let i = 0; i <= 10; i += 1) {
    const a = -Math.PI / 2 + (i * Math.PI) / 5;
    const rr = i % 2 === 0 ? r : r * 0.45;
    out.push({ x: cx + rr * Math.cos(a), y: cy + rr * 1.6 * Math.sin(a) });
  }
  return out;
};

