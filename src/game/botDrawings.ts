function seeded(word: string): () => number {
  let h = 2166136261;
  for (let i = 0; i < word.length; i += 1) {
    h ^= word.charCodeAt(i);
    h = Math.imul(h, 16777619);
  }
  return () => {
    h = Math.imul(h ^ (h >>> 15), 2246822519);
    h = Math.imul(h ^ (h >>> 13), 3266489917);
    return ((h ^= h >>> 16) >>> 0) / 4294967296;
  };
}

function fallback(word: string): Stroke[] {
  const rnd = seeded(word);
  const out: Stroke[] = [];
  const colors = [INK, INK, CYAN, GRAY];
  const n = 4 + Math.floor(rnd() * 3);
  for (let i = 0; i < n; i += 1) {
    const cx = 0.25 + rnd() * 0.5;
    const cy = 0.25 + rnd() * 0.45;
    const color = colors[Math.floor(rnd() * colors.length)];
    if (rnd() < 0.4) {
      out.push(s(circle(cx, cy, 0.05 + rnd() * 0.1), color, 4 + Math.floor(rnd() * 3)));
    } else {
      const raw: Raw[] = [];
      const len = 8 + Math.floor(rnd() * 10);
      let x = cx; let y = cy;
      let a = rnd() * Math.PI * 2;
      for (let j = 0; j < len; j += 1) {
        raw.push([x, y]);
        a += (rnd() - 0.5) * 1.1;
        x = Math.min(0.9, Math.max(0.1, x + Math.cos(a) * 0.045));
        y = Math.min(0.85, Math.max(0.15, y + Math.sin(a) * 0.07));
      }
      out.push(s(pts(...raw), color, 4 + Math.floor(rnd() * 3)));
    }
  }
  return out;
}

export function botDrawingFor(word: string): Stroke[] {
  return DRAWINGS[word.toLowerCase()] ?? fallback(word);
}
